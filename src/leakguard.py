"""공개 공유물 유출 가드 — "자산 규모가 새는 흔적"을 텍스트에서 찾아내는 마지막 방어선.

`scripts/public_page.py` 에 있던 것을 여기로 옮겼다. 공개 페이지 생성기와 공개용 국면
코멘트 생성기(`src/public_brief.py`)가 **같은 가드를 공유**해야 하는데, 둘이 서로를
import 하면 순환이 생기기 때문이다. `scripts.public_page` 는 이 모듈을 재수출해
기존 import 경로(`from scripts.public_page import assert_no_leak`)를 그대로 유지한다.

가드는 백스톱이지 1차 방어선이 아니다 — 1차 방어는 "애초에 담지 않는 것"이다
(수집 화이트리스트, 그리고 브리핑의 경우 **계좌 정보가 없는 컨텍스트로 생성**).
"""
from __future__ import annotations

import re

FOOTER_NOTE = (
    "이 페이지는 공유용으로 자동 생성됩니다. 계좌 잔고·투자 금액·보유 수량 등 자산 규모에 "
    "해당하는 정보는 의도적으로 제외되어 있습니다. 표시된 가격은 시장 가격이며 투자 권유가 "
    "아닙니다."
)

# 각 패턴 = "이게 HTML 에 보이면 자산 규모가 새는 중" 이라는 뜻. 왜 막는지 한 줄씩.
LEAK_PATTERNS: tuple[str, ...] = (
    r"₩[\d,]+",              # 원화 금액 표기 — 잔고·평가금액·손익이 새는 1순위 통로
    r"\$[\d,]+\.\d{2}",      # 달러 금액 표기 — 같은 이유(가격은 통화기호 없이 숫자만 찍는다)
    r"총자산",                # 계좌 총평가 라벨
    r"투입원금",              # 원금 = 이 사람이 넣은 돈
    r"평가손익",              # 손익(원) — 원금 규모를 역산할 수 있다
    r"일손익",                # 당일 손익(원)
    r"평가금액",              # 종목별 평가금액 = 가격×수량
    r"매수여력",              # 주문가능금액 = 현금
    r"현금",                  # 현금 잔고(브레인 코멘트 안의 "현금 N만원" 포함)
    r"수량",                  # 보유 수량 — 가격과 결합하면 자산 규모가 나온다
    r"계좌",                  # 계좌번호·계좌 상태 라벨
    r"order_id",             # 주문 ID — 체결 흔적
    r"주문",                  # 주문/체결 관련 라벨 전반
    r"\b\d{11}\b",           # 계좌번호 자릿수(11자리) — 실번호를 상수로 박지 않고 형태로 잡는다
    r"target_weight",        # decisions payload 원문 — 편입비중은 자본 규모의 대리지표
    r"notional",             # 주문 명목금액
    r"account_seq",          # 계좌 일련번호
    r"C:\\Users",            # 절대경로(운영 PC 사용자명 노출)
    r"/Users/",              # 절대경로(POSIX)
    r"AppData",              # 절대경로 조각
)


def assert_no_leak(html: str) -> list[str]:
    """텍스트에서 블랙리스트 흔적을 찾아 위반 목록을 돌려준다(빈 리스트 = 통과).

    푸터 각주는 "계좌 잔고·보유 수량은 제외했다"는 *설명문*이라 라벨 단어를 그대로 품는다 —
    유일한 예외로 스캔 전에 제거한다(문구가 바뀌면 상수도 같이 바꿔야 걸리지 않는다).
    """
    body = html.replace(FOOTER_NOTE, "")
    out: list[str] = []
    for pat in LEAK_PATTERNS:
        m = re.search(pat, body)
        if m:
            out.append(f"{pat} → {m.group(0)[:40]}")
    return out
